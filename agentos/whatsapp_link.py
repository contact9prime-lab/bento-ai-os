def qr_ascii(payload: str) -> str:
    """The QR as text, for `bento channels whatsapp --link` over SSH.

    Rendered from the same payload the desktop draws as SVG, so the two surfaces
    can never show different codes. Returns '' when there is nothing to draw —
    the caller says why rather than printing an empty box.
    """
    if not payload:
        return ""
    try:
        import qrcode                      # optional; only the TUI path needs it
    except Exception:
        return ""
    q = qrcode.QRCode(border=1)
    q.add_data(payload)
    q.make(fit=True)
    m = q.get_matrix()
    # Two rows per line with half-blocks: a QR drawn one row per line is twice as
    # tall as it is wide in a terminal and will not scan.
    rows = []
    for y in range(0, len(m), 2):
        top, bot = m[y], m[y + 1] if y + 1 < len(m) else [False] * len(m[y])
        rows.append("".join("█" if t and b else "▀" if t else "▄" if b else " "
                            for t, b in zip(top, bot)))
    return "\n".join(rows)
