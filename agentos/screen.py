"""Open Bento on this machine's own screen when it starts: the Office, full screen, listening.

Asked for as "when the Pi has been installed, by default when it loads it opens up Bento in
the client mode with the office, so we can hook it to a screen and start talking to it". The
page already existed (`face.kiosk`, `#kiosk`: the Office full screen with the mic on, only on
the screen plugged into the machine; 24h-kiosk.js). Nothing drew it on a Pi's screen at boot:
Raspberry Pi OS Lite has no desktop at all, and the Install form's Kiosk switch changed only
how the page looks once something opened it.

Two roads, picked by what the machine already has (`road()`):

  * desktop: a display manager is enabled (Raspberry Pi OS with desktop). An XDG autostart
    entry opens the page full screen when the desktop logs in. Nothing system-wide changes
    except the microphone policy.
  * console: no desktop (Raspberry Pi OS Lite). `cage`, a kiosk Wayland compositor (MIT),
    runs Chromium on tty1 from a system unit, as this user, with no login shell anywhere:
    when the browser stops, cage stops and systemd starts it again. It waits, cheaply, for a
    screen to be plugged in and for the server to answer (`wait`), so a Pi with no screen
    pays one sleeping process.

Four rules keep it honest:

  * WHAT RUNS IS WHAT WAS SHOWN. `plan()` lists every change with what it runs; `enable()`
    does exactly those steps and `status()` measures them back. `disable()` undoes all of it.
  * THE PRIVILEGE LADDER. Root steps go through `session._run_root`: passwordless sudo, or a
    password typed at a terminal, else the exact commands handed back. Never a silent change.
  * THE MICROPHONE IS ALLOWED FOR THIS PAGE ONLY, by a Chromium policy naming
    http://127.0.0.1:<port>. Never `--use-fake-ui-for-media-stream`, which would answer yes
    to every page that browser ever shows.
  * NO SHELL ON THE SCREEN. The console road is a unit with a PAM session, never getty
    autologin: a keyboard plugged into the Pi reaches the kiosk, and Ctrl+Alt+F2 still asks
    for a password.

TUI: `bento screen status|on|off`. GUI: Settings → Appearance → On this screen, and the
Install form's "Open on its screen" (install.sh --screen). SUI: not applicable; a machine
whose session IS AgentOS already draws its screen (`bento install-session`).
"""
from __future__ import annotations

import os
import shlex
import shutil
import sys
import time
from pathlib import Path

UNIT_NAME = "bento-screen.service"
UNIT = Path("/etc/systemd/system") / UNIT_NAME
PAM = Path("/etc/pam.d/bento-screen")
# Debian's chromium reads the first, Raspberry Pi's chromium-browser the second.
POLICY_DIRS = (Path("/etc/chromium/policies/managed"), Path("/etc/chromium-browser/policies/managed"))
POLICY_NAME = "bento-screen.json"
AUTOSTART = Path.home() / ".config/autostart" / "bento-screen.desktop"
WAIT_S = 3                 # how often `wait` looks for a screen and the server
DRM = Path("/sys/class/drm")

PAM_TEXT = """\
# Bento on this machine's screen. Generated by `bento screen on`; removed by `bento screen off`.
auth     required pam_unix.so nullok
account  required pam_unix.so
session  required pam_unix.so
session  required pam_systemd.so
"""


def _port(cfg: dict | None = None) -> int:
    if cfg is None:
        from . import config as cfgmod
        cfg = cfgmod.load_config()
    try:
        return int(cfg.get("port") or 8321)
    except (TypeError, ValueError):
        return 8321


def url(cfg: dict | None = None) -> str:
    """The page the screen shows: this machine's own server, as the kiosk."""
    return f"http://127.0.0.1:{_port(cfg)}/#kiosk"


def _linux() -> bool:
    return sys.platform.startswith("linux")


def _run(argv: list[str]) -> tuple[bool, str]:
    from . import session
    return session._run(argv)


def display_manager() -> str:
    """The enabled display manager, or '' on a machine with no desktop."""
    ok, out = _run(["systemctl", "is-enabled", "display-manager.service"])
    if ok and "enabled" in out:
        target = ""
        try:
            target = os.path.basename(os.path.realpath("/etc/systemd/system/display-manager.service"))
        except OSError:
            pass
        return target.removesuffix(".service") or "display manager"
    from . import session
    return session._detect_display_manager()


def road() -> tuple[str, str]:
    """('desktop' | 'console' | '', why)."""
    if not _linux():
        return "", "Opening on the screen at start is for Linux machines like a Raspberry Pi"
    dm = display_manager()
    if dm:
        return "desktop", f"this machine has a desktop ({dm}), so Bento opens when it logs in"
    return "console", "this machine has no desktop, so Bento draws the screen itself with cage"


def screens() -> list[str]:
    """Connectors with a screen plugged in, like 'HDMI-A-1' or 'DSI-1'."""
    out = []
    try:
        for st in sorted(DRM.glob("card*-*/status")):
            try:
                if st.read_text().strip() == "connected":
                    out.append(st.parent.name.split("-", 1)[1])
            except OSError:
                continue
    except OSError:
        pass
    return out


def has_drm() -> bool:
    try:
        return any(DRM.glob("card*-*/status"))
    except OSError:
        return False


def browser() -> str:
    from . import desktop
    return desktop.find_browser() or ""


def _cage() -> str:
    return shutil.which("cage") or ""


def _user() -> str:
    import getpass
    try:
        return getpass.getuser()
    except Exception:
        return os.environ.get("USER", "")


def _python() -> str:
    return sys.executable


def unit_text(cfg: dict | None = None, user: str = "", python: str = "", cage: str = "") -> str:
    """The system unit for the console road. Pure, so the test reads exactly what is written."""
    user = user or _user()
    python = python or _python()
    cage = cage or _cage() or "/usr/bin/cage"
    env = ""
    home = os.environ.get("AGENTOS_HOME")
    if home:
        env = f"Environment=AGENTOS_HOME={home}\n"
    return f"""\
# Bento on this machine's screen. Generated by `bento screen on`; removed by `bento screen off`.
# tty1 shows Bento instead of a login prompt; Ctrl+Alt+F2 still asks for a password.
[Unit]
Description=Bento on this machine's screen
After=systemd-user-sessions.service network-online.target getty@tty1.service
Wants=network-online.target
Conflicts=getty@tty1.service
ConditionPathExists=/dev/tty1

[Service]
User={user}
PAMName=bento-screen
TTYPath=/dev/tty1
TTYReset=yes
TTYVHangup=yes
TTYVTDisallocate=yes
StandardInput=tty-fail
StandardOutput=journal
StandardError=journal
UtmpIdentifier=tty1
UtmpMode=user
{env}ExecStartPre={python} -m agentos screen wait
ExecStart={cage} -s -- {python} -m agentos screen run
Restart=always
RestartSec=5
TimeoutStartSec=infinity

[Install]
WantedBy=multi-user.target
"""


def autostart_text(python: str = "") -> str:
    return f"""\
[Desktop Entry]
Type=Application
Name=Bento on this screen
Comment=Opens Bento full screen, listening, when this machine starts
Exec={python or _python()} -m agentos screen run
Terminal=false
X-GNOME-Autostart-enabled=true
"""


def policy_text(cfg: dict | None = None) -> str:
    import json
    origin = f"http://127.0.0.1:{_port(cfg)}"
    return json.dumps({"AudioCaptureAllowedUrls": [origin], "AutoplayAllowlist": [origin]}, indent=1) + "\n"


def run_argv(cfg: dict | None = None, exe: str = "", profile: str = "") -> list[str]:
    """What `run` starts: the browser full screen on the kiosk, nothing else reachable."""
    from . import config as cfgmod
    exe = exe or browser()
    profile = profile or str(cfgmod.AGENTOS_HOME / "screen-profile")
    args = [exe, "--kiosk", "--noerrdialogs", "--disable-infobars", "--no-first-run",
            "--no-default-browser-check", "--disable-session-crashed-bubble",
            "--disable-translate", "--password-store=basic", _ozone(),
            "--autoplay-policy=no-user-gesture-required",
            "--check-for-update-interval=31536000", f"--user-data-dir={profile}"]
    if hasattr(os, "geteuid") and os.geteuid() == 0:
        args.append("--no-sandbox")       # Chromium refuses to start as root without it
    return args + [url(cfg)]


def _wayland() -> str:
    """The desktop's Wayland socket, or ''. Read from the machine, because a process started
    over SSH or by the installer has no WAYLAND_DISPLAY of its own."""
    run = os.environ.get("XDG_RUNTIME_DIR") or (f"/run/user/{os.getuid()}" if hasattr(os, "getuid") else "")
    name = os.environ.get("WAYLAND_DISPLAY") or "wayland-0"
    return str(Path(run) / name) if run and (Path(run) / name).exists() else ""


def _ozone() -> str:
    # The hint "auto" chose X11 on a Pi's labwc desktop and exited with "Missing X server".
    return "--ozone-platform=wayland" if _wayland() else "--ozone-platform-hint=auto"


def _profile() -> str:
    from . import config as cfgmod
    return str(cfgmod.AGENTOS_HOME / "screen-profile")


def showing() -> list[int]:
    """The screen's browser processes now: the ones using its profile."""
    want = f"--user-data-dir={_profile()}".encode()
    pids = []
    for d in Path("/proc").glob("[0-9]*"):
        try:
            if want in (d / "cmdline").read_bytes():
                pids.append(int(d.name))
        except (OSError, ValueError):
            continue
    return pids


def open_now(cfg: dict | None = None) -> bool:
    """Open it on the desktop that is logged in now, as the autostart will at the next start.
    Only on the desktop road (the console road's unit starts with `enable --now`), and only
    once: True when it was started here."""
    import subprocess
    rd, _ = road()
    if rd != "desktop" or not browser() or showing() or not (_wayland() or os.environ.get("DISPLAY")):
        return False
    subprocess.Popen([_python(), "-m", "agentos", "screen", "run"], stdin=subprocess.DEVNULL,
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
    return True


def close_now() -> int:
    """Close it if it is showing. Returns how many processes were told to stop."""
    import signal
    n = 0
    for pid in showing():
        try:
            os.kill(pid, signal.SIGTERM)
            n += 1
        except OSError:
            pass
    return n


def restart_now(cfg: dict | None = None, wait: float = 6.0) -> str:
    """Start the screen's browser again: it was left on its own "not reachable" page, where
    nothing of ours runs to reload it. On the console road cage ends with the browser and
    systemd starts it again (Restart=always); on a desktop it is opened here once it has gone.
    Returns what happened, in words."""
    if not close_now():
        return "no browser was showing Bento on this screen"
    t0 = time.time()
    while showing() and time.time() - t0 < wait:
        time.sleep(0.3)
    rd, _ = road()
    if rd == "desktop":
        return "started the screen's browser again" if open_now(cfg) else \
            "closed the screen's browser, and could not open it again here"
    return "started the screen's browser again"


def _server_up(cfg: dict | None = None) -> bool:
    from . import desktop
    return desktop._server_up(_port(cfg))


def wait(cfg: dict | None = None, timeout: float = 0, sleep=time.sleep) -> bool:
    """Block until a screen is plugged in and the server answers. A machine whose kernel
    reports no connectors at all (some boards, a VM) counts as having its screen."""
    t0 = time.time()
    while True:
        if (screens() or not has_drm()) and _server_up(cfg):
            return True
        if timeout and time.time() - t0 > timeout:
            return False
        sleep(WAIT_S)


def run(cfg: dict | None = None) -> None:
    """Wait for the server, then become the browser (exec), so cage's child is Chromium."""
    exe = browser()
    if not exe:
        sys.exit("no Chromium here to draw the screen with: `bento screen on` installs it")
    wait(cfg, timeout=600)
    args = run_argv(cfg, exe)
    from . import config as cfgmod
    (cfgmod.AGENTOS_HOME / "screen-profile").mkdir(parents=True, exist_ok=True)
    sock = _wayland()
    if sock:
        os.environ.setdefault("XDG_RUNTIME_DIR", str(Path(sock).parent))
        os.environ.setdefault("WAYLAND_DISPLAY", Path(sock).name)
    os.execv(exe, args)


# ---- status, plan, enable, disable ---------------------------------------------------------

def _moved_app_autostart() -> Path:
    from . import desktop
    return desktop.AUTOSTART_FILE.with_name(desktop.AUTOSTART_FILE.name + ".bento-screen")


def status(cfg: dict | None = None) -> dict:
    """What is true now, measured: never a note that a run once ended."""
    rd, why = road()
    on = False
    if rd == "console":
        on = UNIT.exists() and _run(["systemctl", "is-enabled", UNIT_NAME])[0]
    elif rd == "desktop":
        on = AUTOSTART.exists()
    have = screens()
    missing = []
    if rd == "console" and not _cage():
        missing.append("cage")
    if rd and not browser():
        missing.append("chromium")
    if not rd:
        words = why
    elif on:
        words = ("Opens on this screen when the machine starts"
                 + ("" if have or not has_drm() else ", once a screen is plugged in"))
    else:
        words = "Off: this machine's screen shows " + ("its desktop" if rd == "desktop" else "a login prompt")
    return {"on": on, "road": rd, "why": why, "screens": have, "missing": missing,
            "browser": browser(), "url": url(cfg), "words": words,
            "policy": any((d / POLICY_NAME).exists() for d in POLICY_DIRS)}


def plan(cfg: dict | None = None) -> list[dict]:
    """Every change `enable()` makes, in order, with what it runs."""
    from . import components
    rd, _ = road()
    steps: list[dict] = []
    if not rd:
        return steps
    need = ["cage"] if rd == "console" and not _cage() else []
    if not browser():
        need.append("chromium")
    words = {"cage": ("Install cage", "A small compositor that shows one app full screen on a machine "
                                      "with no desktop."),
             "chromium": ("Install Chromium", "The browser that draws the page on the screen.")}
    for cid in need:
        comp = components.CATALOG.get(cid) or {}
        title, why = words[cid]
        steps.append({"id": f"install-{cid}", "root": True, "title": title,
                      "why": f"{why} Licence: {comp.get('licence', '?')}.",
                      "runs": components.install_command(comp) or f"install {cid}"})
    dirs = " ".join(shlex.quote(str(d)) for d in POLICY_DIRS)
    mic = {"id": "mic", "root": True, "title": "Let this page use the microphone",
           "why": f"Chromium allows the mic for {url(cfg).split('/#')[0]} only, so the screen "
                  "can hear you without a prompt nobody can answer.",
           "runs": f"mkdir -p {dirs}; write {POLICY_NAME} in each"}
    if rd == "console":
        steps.append(mic)
    if rd == "console":
        steps.append({"id": "pam", "root": True, "title": "A login session for the screen",
                      "why": "Gives the screen its seat (display and input) without logging a shell in.",
                      "runs": f"write {PAM}"})
        steps.append({"id": "unit", "root": True, "title": "Start Bento on tty1 at boot",
                      "why": "tty1 shows Bento instead of a login prompt. Ctrl+Alt+F2 still asks for "
                             "a password.",
                      "runs": f"write {UNIT}; systemctl daemon-reload; systemctl enable --now {UNIT_NAME}"})
    else:
        steps.append({"id": "autostart", "root": False, "title": "Open Bento when the desktop logs in",
                      "why": "Full screen, as the kiosk. It needs the desktop to log in by itself "
                             "(Raspberry Pi OS does unless you turned that off).",
                      "runs": f"write {AUTOSTART}"})
        # After the autostart: on a desktop the page opens without it and asks for the mic
        # once, so a Pi whose sudo wants a password still gets its screen.
        steps.append(mic)
    return steps


def _root_write(path: Path, text: str, why: str) -> tuple[bool, str]:
    """Write a root-owned file through the ladder: staged in our home, copied with sudo."""
    from . import config as cfgmod
    from . import session
    stage = cfgmod.AGENTOS_HOME / f".stage-{path.name}"
    stage.parent.mkdir(parents=True, exist_ok=True)
    stage.write_text(text)
    try:
        ok, out = session._run_root(["install", "-D", "-m", "0644", str(stage), str(path)], why)
        return ok, out
    finally:
        stage.unlink(missing_ok=True)


def _handback(cfg: dict | None, rd: str) -> list[str]:
    """The exact commands for somebody to run when this process cannot get root."""
    lines = []
    from . import components
    for cid in (["cage"] if rd == "console" and not _cage() else []) + ([] if browser() else ["chromium"]):
        cmd = components.install_command(components.CATALOG.get(cid) or {})
        if cmd:
            lines.append(f"sudo {cmd}")
    # never `sudo bento screen on`: as root it would write the unit for root, not for you
    lines.append("bento screen on   # at a terminal on this machine: it asks for your password")
    return lines


def enable(cfg: dict | None = None, say=print) -> dict:
    """Do `plan()`. Returns {ok, done, needs: [commands], error}."""
    import asyncio

    from . import components
    from . import session
    rd, why = road()
    if not rd:
        return {"ok": False, "done": [], "needs": [], "error": why}
    done = []
    for step in plan(cfg):
        say(f"→ {step['title']}")
        if step["id"].startswith("install-"):
            cid = step["id"].split("-", 1)[1]
            got = asyncio.run(components.install(cid))
            if not got.get("ok"):
                return {"ok": False, "done": done, "error": got.get("message") or f"could not install {cid}",
                        "needs": [got["command"]] if got.get("command") else _handback(cfg, rd)}
        elif step["id"] == "mic":
            for d in POLICY_DIRS:
                ok, out = _root_write(d / POLICY_NAME, policy_text(cfg),
                                      "Bento needs root to let its own page use the microphone.")
                if not ok and rd == "desktop":
                    return {"ok": True, "done": done, "needs": _handback(cfg, rd), "error": "",
                            "mic": "root is needed to let the page use the microphone without asking"}
                if not ok:
                    return {"ok": False, "done": done, "needs": _handback(cfg, rd),
                            "error": "root is needed to let the page use the microphone" + (f" ({out})" if out else "")}
        elif step["id"] == "pam":
            ok, out = _root_write(PAM, PAM_TEXT, "Bento needs root to give the screen a login session.")
            if not ok:
                return {"ok": False, "done": done, "needs": _handback(cfg, rd), "error": out or "root is needed"}
        elif step["id"] == "unit":
            ok, out = _root_write(UNIT, unit_text(cfg), "Bento needs root to start on the screen at boot.")
            if not ok:
                return {"ok": False, "done": done, "needs": _handback(cfg, rd), "error": out or "root is needed"}
            cmds = (["systemctl", "daemon-reload"], ["systemctl", "enable", "--now", UNIT_NAME])
            for i, argv in enumerate(cmds):
                ok, out = session._run_root(argv, "Bento needs root to start on the screen at boot.")
                if not ok:
                    # the files are written; what is left is exactly these
                    return {"ok": False, "done": done, "needs": [f"sudo {' '.join(a)}" for a in cmds[i:]],
                            "error": f"{' '.join(argv)} failed: {(out or '').splitlines()[0].rstrip('.') if out else 'no answer'}"}
        elif step["id"] == "autostart":
            from . import desktop
            if desktop.AUTOSTART_FILE.exists():        # one window at login, not two
                desktop.AUTOSTART_FILE.replace(_moved_app_autostart())
            AUTOSTART.parent.mkdir(parents=True, exist_ok=True)
            AUTOSTART.write_text(autostart_text())
        done.append(step["id"])
        say(f"✓ {step['title']}")
    return {"ok": True, "done": done, "needs": [], "error": ""}


def disable(cfg: dict | None = None, say=print) -> dict:
    """Undo all of it: the unit, the PAM file, the policy, the autostart."""
    from . import session
    removed, needs, error = [], [], ""
    if AUTOSTART.exists():
        AUTOSTART.unlink()
        removed.append(str(AUTOSTART))
        moved = _moved_app_autostart()
        if moved.exists():
            from . import desktop
            moved.replace(desktop.AUTOSTART_FILE)
    root_paths = [p for p in (UNIT, PAM, *(d / POLICY_NAME for d in POLICY_DIRS)) if p.exists()]
    if UNIT.exists():
        ok, out = session._run_root(["systemctl", "disable", "--now", UNIT_NAME],
                                    "Bento needs root to stop drawing the screen.")
        if not ok:
            needs.append(f"sudo systemctl disable --now {UNIT_NAME}")
            error = f"systemctl disable failed: {(out or 'no answer').splitlines()[0].rstrip('.')}"
    for p in root_paths:
        ok, out = session._run_root(["rm", "-f", str(p)], "Bento needs root to remove its screen files.")
        (removed if ok else needs).append(str(p) if ok else f"sudo rm -f {p}")
        if not ok and not error:
            error = f"could not remove {p}: {(out or 'root is needed').splitlines()[0].rstrip('.')}"
    if root_paths:
        session._run_root(["systemctl", "daemon-reload"], "Bento needs root to reload systemd.")
    for r in removed:
        say(f"✓ removed {r}")
    # a mic policy left behind only lets this page use the mic; the screen is off without it
    stops = [n for n in needs if POLICY_NAME not in n]
    return {"ok": not stops, "removed": removed, "needs": needs, "error": error if stops else ""}
